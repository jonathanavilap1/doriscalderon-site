// Generates src/types.generated.ts from schemas/*.schema.json.
// `--check` fails (for CI) when the committed file is stale.
import { compile } from 'json-schema-to-typescript';
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(fileURLToPath(import.meta.url));
const schemaDir = path.join(root, '..', 'schemas');
const out = path.join(root, '..', 'src', 'types.generated.ts');
const check = process.argv.includes('--check');

const files = (await readdir(schemaDir)).filter((f) => f.endsWith('.schema.json')).sort();
let body = '/* eslint-disable */\n// GENERATED by scripts/generate-types.mjs from schemas/*.schema.json. Do not edit.\n\n';

for (const file of files) {
  const schema = JSON.parse(await readFile(path.join(schemaDir, file), 'utf8'));
  body += await compile(schema, schema.title, {
    cwd: schemaDir,
    bannerComment: '',
    additionalProperties: false,
    declareExternallyReferenced: false,
    maxItems: -1,
  });
}

if (check) {
  const current = await readFile(out, 'utf8').catch(() => '');
  if (current !== body) {
    console.error('types.generated.ts is stale. Run `npm run generate` in /contracts.');
    process.exit(1);
  }
} else {
  await writeFile(out, body);
  console.log(`wrote ${path.relative(process.cwd(), out)}`);
}
